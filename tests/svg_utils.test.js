import test from 'node:test';
import assert from 'node:assert/strict';
import {
  convertSvgToCurrentColor,
  decodeSvgDataUrl,
  extractSvgPalette,
  extractSymbolFromSvgSprite,
  normalizeSvgColor,
  optimizeSvgMarkup,
  replaceSvgColor,
  splitSvgSpriteUrl
} from '../src/shared/svg_utils.js';

test('optimizeSvgMarkup strips XML prologs, comments, metadata, event handlers, and empty defs', () => {
  const dirty = [
    '\uFEFF<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">',
    '<!-- generated by designer -->',
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" onload="alert(1)">',
    '  <metadata><rdf:RDF>info</rdf:RDF></metadata>',
    '  <defs>   </defs>',
    '  <path d="M0 0h24v24H0z" onclick="steal()" />',
    '</svg>'
  ].join('\n');

  const optimized = optimizeSvgMarkup(dirty);
  assert.equal(optimized.includes('<?xml'), false);
  assert.equal(optimized.includes('<!DOCTYPE'), false);
  assert.equal(optimized.includes('<!--'), false);
  assert.equal(optimized.includes('<metadata'), false);
  assert.equal(optimized.includes('<defs'), false);
  assert.equal(optimized.includes('onload='), false);
  assert.equal(optimized.includes('onclick='), false);
  assert.equal(
    optimized,
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path d="M0 0h24v24H0z" /></svg>'
  );
});

test('extractSymbolFromSvgSprite extracts targeted symbol with viewBox and sprite defs', () => {
  const sprite = [
    '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">',
    '  <defs><linearGradient id="g1"><stop offset="0%" stop-color="#000"/></linearGradient></defs>',
    '  <symbol id="icon-home" viewBox="0 0 32 32">',
    '    <!-- comment inside symbol -->',
    '    <path fill="url(#g1)" d="M4 16L16 4l12 12v12H4z"/>',
    '  </symbol>',
    '  <symbol id="icon-bell" viewBox="0 0 16 16">',
    '    <circle cx="8" cy="8" r="6"/>',
    '  </symbol>',
    '</svg>'
  ].join('\n');

  const bell = extractSymbolFromSvgSprite(sprite, 'icon-bell');
  assert.match(bell, /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="0 0 16 16">/);
  assert.equal(bell.includes('<defs><linearGradient id="g1">'), true);
  assert.equal(bell.includes('<circle cx="8" cy="8" r="6"/>'), true);
  assert.equal(bell.includes('icon-home'), false);

  assert.equal(extractSymbolFromSvgSprite(sprite, 'missing-id'), '');
});

test('splitSvgSpriteUrl separates base URL and URL-encoded fragment symbol id', () => {
  assert.deepEqual(
    splitSvgSpriteUrl('https://cdn.example.com/icons/sprite.svg?v=2#arrow%20right'),
    {
      baseUrl: 'https://cdn.example.com/icons/sprite.svg?v=2',
      symbolId: 'arrow right'
    }
  );
  assert.deepEqual(
    splitSvgSpriteUrl('data:image/svg+xml;utf8,<svg></svg>'),
    {
      baseUrl: 'data:image/svg+xml;utf8,<svg></svg>',
      symbolId: ''
    }
  );
});

test('decodeSvgDataUrl handles base64 and percent-encoded SVG data URIs', () => {
  const raw = '<svg xmlns="http://www.w3.org/2000/svg"><rect width="10" height="10"/></svg>';
  const b64 = `data:image/svg+xml;base64,${Buffer.from(raw, 'utf8').toString('base64')}`;
  const pct = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(raw)}`;

  assert.equal(decodeSvgDataUrl(b64), raw);
  assert.equal(decodeSvgDataUrl(pct), raw);
});

test('normalizeSvgColor, extractSvgPalette, replaceSvgColor, and convertSvgToCurrentColor recolor SVGs cleanly', () => {
  assert.equal(normalizeSvgColor('#AbC'), '#aabbcc');
  assert.equal(normalizeSvgColor('rgb(255, 0, 128)'), '#ff0080');
  assert.equal(normalizeSvgColor('none'), '');
  assert.equal(normalizeSvgColor('url(#grad1)'), '');

  const svg = '<svg><path fill="#F00" stroke="rgb(0, 128, 255)"/><rect style="fill:#0f0;stroke:none"/><circle fill="currentColor"/></svg>';
  assert.deepEqual(extractSvgPalette(svg), ['#ff0000', '#0080ff', '#00ff00']);

  const recolored = replaceSvgColor(svg, '#ff0000', '#123456');
  assert.equal(recolored.includes('fill="#123456"'), true);
  assert.equal(recolored.includes('stroke="rgb(0, 128, 255)"'), true);

  const mono = convertSvgToCurrentColor(svg);
  assert.deepEqual(extractSvgPalette(mono), []);
  assert.equal(mono.includes('fill="currentColor"'), true);
  assert.equal(mono.includes('stroke:none'), true);
});
